def grid(h, w, fills, floor=(), E=None):
    g = [list('#' * w) for _ in range(h)]
    for ch, r0, r1, c0, c1 in fills:
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1): g[r][c] = ch
    for r, c0, c1 in floor:
        for c in range(c0, c1 + 1): g[r][c] = '.'
    g[E[0]][E[1]] = 'E'
    return [''.join(x) for x in g]
